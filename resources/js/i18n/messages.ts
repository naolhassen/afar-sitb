export function tf<T extends Record<string, any>>(
  item: T | null | undefined,
  field: string,
  locale: Locale
): string {
  if (!item) return '';
  const suffix = locale === 'af' ? 'Af' : locale === 'am' ? 'Am' : 'En';
  const val = item[field + suffix];
  if (val) return val;
  return item[field + 'En'] || item[field + 'Am'] || item[field + 'Af'] || '';
}
