const suffix: Record<Locale, string> = { af: 'Af', am: 'Am', en: 'En' };

export function tf(
  record: any,
  field: string,
  locale: Locale
): string {
  if (!record) return '';
  const key = `${field}${suffix[locale]}`;
  const val = record[key];
  if (val !== undefined && val !== null && String(val).trim() !== '') {
    return String(val);
  }
  // Fallbacks: Try En, then Am, then Af
  const fallbackOrder = ['En', 'Am', 'Af'];
  for (const s of fallbackOrder) {
    const fVal = record[`${field}${s}`];
    if (fVal !== undefined && fVal !== null && String(fVal).trim() !== '') {
      return String(fVal);
    }
  }
  return '';
}
